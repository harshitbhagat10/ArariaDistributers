let currentLang=localStorage.getItem('electroshop_lang')||'en';

function t(key){
  return (LANG[currentLang]&&LANG[currentLang][key])||LANG.en[key]||key;
}

// Map English category names to translation keys
const CAT_KEY_MAP={'Mobile & Tablets':'cat.mobile','TV & Display':'cat.tv','Laptops':'cat.laptops','Audio':'cat.audio','Cameras':'cat.cameras','Gaming':'cat.gaming','Home Appliances':'cat.home','Accessories':'cat.accessories','Networking':'cat.networking'};
function tCat(name){ return CAT_KEY_MAP[name]?t(CAT_KEY_MAP[name]):name; }

function applyLang(lang){
  currentLang=lang;
  localStorage.setItem('electroshop_lang',lang);
  // Update all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key=el.getAttribute('data-i18n');
    const txt=t(key);
    if(el.tagName==='INPUT'||el.tagName==='TEXTAREA'){
      el.placeholder=txt;
    } else if(el.tagName==='OPTION'){
      el.textContent=txt;
    } else {
      el.innerHTML=txt;
    }
  });
  // Update lang toggle button
  const lb=document.getElementById('lang-btn');
  if(lb) lb.textContent=t('lang.label');
  // Re-render active page to translate dynamic content
  const activeSection=document.querySelector('.section.active');
  if(activeSection){
    const id=activeSection.id.replace('tab-','');
    if(id==='dash')renderDash();
    if(id==='inv'){populateCatFilter();renderInv();}
    if(id==='hist')renderHist();
    if(id==='report')renderReport();
    if(id==='staff')initStaffTab();
    if(id==='admin'){renderAdjLog();renderLowStockList();}
    if(id==='perf')renderStaffPerf();
    if(id==='profile')renderProfile();
  }
}

function toggleLang(){
  applyLang(currentLang==='en'?'hi':'en');
}
